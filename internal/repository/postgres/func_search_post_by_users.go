package postgres

import (
	"context"
	"errors"
	"net/http"

	"github.com/QuentinRegnier/numan-backend/internal/domain/numan_error"
	"github.com/QuentinRegnier/numan-backend/internal/domain/numan_log"
	"github.com/QuentinRegnier/numan-backend/internal/infrastructure/postgres"
	"github.com/lib/pq"
)

// FuncSearchPostIDsByUsers appelle la procédure SQL de recherche pour un panel d'utilisateurs avec tri.
func FuncSearchPostIDsByUsers(ctx context.Context, userIDs []int64, orderMode int, offset, limit int64) ([]int64, error) {
	if len(userIDs) == 0 {
		return []int64{}, nil
	}

	if postgres.PostgresDB == nil {
		return nil, numan_error.NewAppError(
			http.StatusInternalServerError,
			numan_error.CodeDatabaseError,
			"Le service de base de données est momentanément indisponible.",
			errors.New("PostgreSQL connection 'PostgresDB' is not initialized"),
		)
	}

	query := `SELECT id FROM content.func_search_post_ids_by_users($1, $2::smallint, $3::integer, $4::integer)`
	rows, err := postgres.PostgresDB.QueryContext(ctx, query, pq.Array(userIDs), orderMode, offset, limit)
	if err != nil {
		return nil, numan_error.NewAppError(
			http.StatusInternalServerError,
			numan_error.CodeDatabaseError,
			"Impossible de rechercher les publications par utilisateurs.",
			err,
		)
	}
	defer func() {
		if err := rows.Close(); err != nil {
			numan_log.Error(ctx).Err(err).Msg("Impossible de fermer le curseur SQL, risque de fuite de connexion au pool")
		}
	}()

	ids := make([]int64, 0)
	for rows.Next() {
		var id int64
		if err := rows.Scan(&id); err == nil {
			ids = append(ids, id)
		}
	}

	if err := rows.Err(); err != nil {
		return nil, numan_error.NewAppError(
			http.StatusInternalServerError,
			numan_error.CodeDatabaseError,
			"Impossible d'itérer sur la recherche des publications par utilisateurs.",
			err,
		)
	}

	return ids, nil
}
